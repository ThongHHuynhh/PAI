// Package atomicfile writes files so a reader sees the old content or the new,
// never a part: write a temporary file beside the target, sync it, rename it.
package atomicfile

import (
	"encoding/json"
	"os"
	"path/filepath"
)

// Write replaces path with b. The directory is created when missing.
func Write(path string, b []byte, perm os.FileMode) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	f, err := os.CreateTemp(dir, "."+filepath.Base(path)+".tmp-*")
	if err != nil {
		return err
	}
	tmp := f.Name()
	defer os.Remove(tmp) // a no-op after the rename
	if _, err := f.Write(b); err != nil {
		f.Close()
		return err
	}
	if err := f.Sync(); err != nil {
		f.Close()
		return err
	}
	if err := f.Close(); err != nil {
		return err
	}
	if err := os.Chmod(tmp, perm); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// WriteJSON writes v indented, with a trailing newline.
func WriteJSON(path string, v any, perm os.FileMode) error {
	b, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	return Write(path, append(b, '\n'), perm)
}

// ReadJSON reads path into v. A missing file leaves v alone and returns
// os.ErrNotExist wrapped, so callers can tell "none yet" from "broken".
func ReadJSON(path string, v any) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	return json.Unmarshal(b, v)
}
